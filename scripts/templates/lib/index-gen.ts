import * as fs from 'fs';

import { listPackKeys, packPath, readManifest, TEMPLATES_DIR } from './pack';

const HEADER = '// Generated by `pnpm template:index`; do not edit.\n';

const importName = (index: number) => `manifest${index}`;

export function renderManifestsModule(keys: string[]): string {
    const imports = keys
        .map(
            (key, i) => `import ${importName(i)} from "./${key}/manifest.json";`
        )
        .join('\n');

    const entries = keys
        .map((key, i) => `  "${key}": ${importName(i)},`)
        .join('\n');

    return `${HEADER}${imports}\n\nexport const MANIFESTS = {\n${entries}\n} as const;\n`;
}

export function renderDictionariesModule(
    packs: { key: string; locales: string[] }[]
): string {
    const entries = packs
        .filter((pack) => pack.locales.length > 0)
        .map(
            (pack) =>
                `  "${pack.key}": {\n${pack.locales.map((locale) => `    ${locale}: () => import("./${pack.key}/i18n/${locale}.json"),`).join('\n')}\n  },`
        )
        .join('\n');

    return `${HEADER}import "server-only";\n\nexport const DICTIONARY_LOADERS: Record<string, Partial<Record<string, () => Promise<{ default: unknown }>>>> = {\n${entries}\n};\n`;
}

export function writeIndex(dir = TEMPLATES_DIR): void {
    const keys = listPackKeys(dir);

    const packs = keys.map((key) => ({
        key,
        locales: readManifest(key, dir)
            .locales.filter((locale) => locale !== 'en')
            .filter((locale) =>
                fs.existsSync(packPath(key, `i18n/${locale}.json`, dir))
            ),
    }));

    fs.writeFileSync(`${dir}/manifests.ts`, renderManifestsModule(keys));
    fs.writeFileSync(
        `${dir}/dictionaries.server.ts`,
        renderDictionariesModule(packs)
    );
}
