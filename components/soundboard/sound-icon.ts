import {
    Beer,
    Bell,
    Bomb,
    CloudLightning,
    Coins,
    DoorClosed,
    DoorOpen,
    Flame,
    Footprints,
    GlassWater,
    HeartPulse,
    type LucideIcon,
    Megaphone,
    PackageOpen,
    PartyPopper,
    PawPrint,
    Skull,
    Sparkles,
    Sword,
    Swords,
    Target,
    Volume2,
} from 'lucide-react';

const ICONS: Record<string, LucideIcon> = {
    'door-open': DoorOpen,
    'door-closed': DoorClosed,
    swords: Swords,
    sword: Sword,
    target: Target,
    'cloud-lightning': CloudLightning,
    bomb: Bomb,
    flame: Flame,
    sparkles: Sparkles,
    'heart-pulse': HeartPulse,
    'paw-print': PawPrint,
    beer: Beer,
    footprints: Footprints,
    megaphone: Megaphone,
    coins: Coins,
    bell: Bell,
    'package-open': PackageOpen,
    'glass-water': GlassWater,
    skull: Skull,
    'party-popper': PartyPopper,
};

export const soundIcon = (name: string | null): LucideIcon =>
    (name && ICONS[name]) || Volume2;
