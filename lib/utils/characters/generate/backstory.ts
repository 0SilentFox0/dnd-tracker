export function generateBackstory(
  input: { name: string; raceName: string; archetype: HeroArchetypeKey },
  rng: () => number,
): { background: string; goals: Array<{ text: string; kind: GoalKind }> } {
  const place = input.raceName ? `серед народу ${input.raceName}` : "у далеких землях";

  const origin = pick(rng, ORIGIN)({ name: input.name, place });

  const turn = pick(rng, TURN[input.archetype]);

  const drive = pick(rng, DRIVE);

  return {
    background: [origin, turn, drive].join(" "),
    goals: [
      { kind: GoalKind.MAIN, text: pick(rng, MAIN_GOALS) },
      { kind: GoalKind.PERSONAL, text: pick(rng, PERSONAL_GOALS) },
    ],
  };
}
